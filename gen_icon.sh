#!/bin/sh
# Generate the 4 MicroDLNA tray icon files (small/large, PNG/JPEG) and the
# matching icons.h, for use with `make ICON=<name>`.
#
# Usage:
#   ./gen_icon.sh <name> <source-image>
#       Convert <source-image> into the 4 icon files with ImageMagick,
#       then pack them into icons/<name>/icons.h.
#   ./gen_icon.sh --pack <name>
#       Skip the ImageMagick conversion; pack the 4 files already present
#       in icons/<name>/ into icons/<name>/icons.h.

set -e

ICON_SM_W=41
ICON_SM_H=48
ICON_LRG_W=102
ICON_LRG_H=120

usage() {
    echo "Usage: $0 <name> <source-image>" >&2
    echo "       $0 --pack <name>" >&2
    exit 1
}

pack_only=0
if [ "$1" = "--pack" ]; then
    pack_only=1
    shift
fi

if [ "$pack_only" = 1 ]; then
    [ $# -eq 1 ] || usage
    name=$1
else
    [ $# -eq 2 ] || usage
    name=$1
    src=$2
fi

case "$name" in
    *[!A-Za-z0-9_]*|"")
        echo "Error: icon name '$name' must be a valid C identifier (letters, digits, underscore)" >&2
        exit 1
        ;;
esac

dir="icons/$name"
mkdir -p "$dir"

if [ "$pack_only" = 0 ]; then
    [ -f "$src" ] || { echo "Error: source image '$src' not found" >&2; exit 1; }
    command -v convert >/dev/null 2>&1 || { echo "Error: ImageMagick 'convert' not found" >&2; exit 1; }

    convert "$src" -background white -flatten -resize "${ICON_SM_W}x${ICON_SM_H}!" \
        -colors 256 -type Palette "$dir/${name}_sm.png"
    convert "$src" -background white -flatten -resize "${ICON_LRG_W}x${ICON_LRG_H}!" \
        -colors 256 -type Palette "$dir/${name}_lrg.png"
    convert "$src" -resize "${ICON_SM_W}x${ICON_SM_H}!" -background white -flatten \
        -quality 95 -sampling-factor 2x2,1x1,1x1 "$dir/${name}_sm.jpg"
    convert "$src" -resize "${ICON_LRG_W}x${ICON_LRG_H}!" -background white -flatten \
        -quality 95 -sampling-factor 2x2,1x1,1x1 "$dir/${name}_lrg.jpg"
fi

for f in "${name}_sm.png" "${name}_lrg.png" "${name}_sm.jpg" "${name}_lrg.jpg"; do
    [ -f "$dir/$f" ] || { echo "Error: expected file '$dir/$f' not found" >&2; exit 1; }
done

command -v xxd >/dev/null 2>&1 || { echo "Error: 'xxd' not found" >&2; exit 1; }

out="$dir/icons.h"
{
    echo "#pragma once"
    echo "/* Generated by gen_icon.sh -- do not edit by hand. */"
    echo
} > "$out"

emit() {
    file=$1      # e.g. tux_sm.png
    mangled=$2   # e.g. tux_sm_png (as produced by xxd -i)
    canon=$3     # e.g. png_sm
    (cd "$dir" && xxd -i "$file") \
        | sed -e "s/^unsigned char ${mangled}\[\]/static unsigned char ${canon}[]/" \
        | grep -v "^unsigned int ${mangled}_len" \
        >> "$out"
    echo >> "$out"
}

emit "${name}_sm.png"  "${name}_sm_png"  png_sm
emit "${name}_lrg.png" "${name}_lrg_png" png_lrg
emit "${name}_sm.jpg"  "${name}_sm_jpg"  jpeg_sm
emit "${name}_lrg.jpg" "${name}_lrg_jpg" jpeg_lrg

echo "Generated $dir/ (4 images + icons.h)"
