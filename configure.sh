#!/bin/sh

# Icon set used to resolve icons.h while scanning dependencies below; the
# actual default used by the generated Makefile is set once and for all in
# the "ICON ?= ..." line it emits further down.
default_icon=clap

tab=$(printf '\t')
objs=$(ls -1 *.c | grep -v version | sed -e 's|\.c$|.o|' | tr '\n' ' ')
build_objs=$(echo "$objs" | sed -e 's|\([a-zA-Z0-9_]*\.o\)|\$(BUILD_DIR)/\1|g')

exec 1> Makefile

cat <<MAKEFILE
# Build type: dev (default) | release
#   make release  -> -O3, LTO, -ffunction-sections -fdata-sections, --gc-sections, sans -g
#   make           -> -O2, -g (débogage)
BUILD ?= dev
BUILD_DIR := build

# Icon set used at build time: a directory icons/<ICON>/ must contain the
# icons.h generated by ./gen_icon.sh (see icons/$default_icon/ for the default set).
ICON ?= $default_icon

BASE_CFLAGS := --std=c11 -D_GNU_SOURCE -D_LARGEFILE_SOURCE -D_FILE_OFFSET_BITS=64 -Iicons/\$(ICON)
CFLAGS_DEV := \$(BASE_CFLAGS) -g -O2
CFLAGS_RELEASE := \$(BASE_CFLAGS) -O3 -flto -ffunction-sections -fdata-sections
LDFLAGS_DEV := -pthread
LDFLAGS_RELEASE := -pthread -flto -Wl,--gc-sections

ifeq (\$(BUILD),release)
  CFLAGS := \$(CFLAGS_RELEASE)
  LDFLAGS := \$(LDFLAGS_RELEASE)
else
  CFLAGS := \$(CFLAGS_DEV)
  LDFLAGS := \$(LDFLAGS_DEV)
endif

DST := $build_objs version.c

.PHONY: all
all: \$(BUILD_DIR)/microdlnad \$(BUILD_DIR)/microdlnad.8

MAKEFILE

# run the compiler to find dependancies
printf 'deps:\n\t@$(CC) -MM -MG -Iicons/%s -MF - -c *.c\n' "$default_icon" | make -f - \
    | sed -e 's|version\.o|\$(BUILD_DIR)/microdlnad|' \
    | sed -e 's|version_info\.h|gen_version.sh|' \
    | sed -e "s|icons/$default_icon/icons\\.h|icons/\\\$(ICON)/icons.h|" \
    | sed -e '/upnphttp\.o:/{ :a; /\\$/{ N; ba }; s|$| \$(BUILD_DIR)/.icon| }' \
    | sed -e 's|^\([a-zA-Z0-9_]*\.o\)|\$(BUILD_DIR)/\1|'

cat <<MAKEFILE

\$(BUILD_DIR):
${tab}mkdir -p \$(BUILD_DIR)

.PHONY: FORCE
FORCE:

\$(BUILD_DIR)/.icon: FORCE | \$(BUILD_DIR)
${tab}@if [ ! -f \$@ ] || [ "\$\$(cat \$@)" != "\$(ICON)" ]; then \\
${tab}${tab}echo "\$(ICON)" > \$@; \\
${tab}fi

\$(BUILD_DIR)/%.o: %.c | \$(BUILD_DIR)
${tab}\$(CC) -c \$(CFLAGS) \$< -o \$@

\$(BUILD_DIR)/microdlnad: \$(DST) | \$(BUILD_DIR)
${tab}./gen_version.sh > \$(BUILD_DIR)/version_info.h
${tab}\$(CC) \$(CFLAGS) -I\$(BUILD_DIR) -o \$(BUILD_DIR)/microdlnad \$(DST) \$(LDFLAGS)

\$(BUILD_DIR)/microdlnad.8: microdlna.pod | \$(BUILD_DIR)
${tab}pod2man -c multimedia -r '' microdlna.pod > \$(BUILD_DIR)/microdlnad.8

.PHONY: clean
clean:
${tab}rm -rf \$(BUILD_DIR)

.PHONY: install
install:
${tab}mkdir -p /usr/local/bin
${tab}cp \$(BUILD_DIR)/microdlnad /usr/local/bin
${tab}strip /usr/local/bin/microdlnad
${tab}mkdir -p /usr/local/share/man/man8
${tab}cp \$(BUILD_DIR)/microdlnad.8 /usr/local/share/man/man8

# ---- tests --------------------------------------------------------------
# tests/test_<module>.c "#include"s ../<module>.c to reach its static
# functions, so <module>.o is excluded from that binary's link (see
# tests/support/ and docs/dev/TESTS.md). microdlna.o is never linked into a
# test binary (it holds main() and the production globals, stubbed in
# tests/support/stubs.c). ASan/UBSan/LeakSanitizer are always on for tests;
# they never affect the production binary built by \$(BUILD_DIR)/microdlnad.
TEST_DIR := tests
TEST_OBJ_DIR := \$(BUILD_DIR)/tests/obj
TEST_BIN_DIR := \$(BUILD_DIR)/tests/bin

TEST_SRCS := \$(wildcard \$(TEST_DIR)/test_*.c)
TEST_BINS := \$(patsubst \$(TEST_DIR)/test_%.c,\$(TEST_BIN_DIR)/test_%,\$(TEST_SRCS))
TEST_SUPPORT_OBJS := \$(TEST_OBJ_DIR)/support_test_main.o \\
                     \$(TEST_OBJ_DIR)/support_stubs.o \\
                     \$(TEST_OBJ_DIR)/support_helpers.o
TEST_MODULE_OBJS := \$(patsubst \$(BUILD_DIR)/%.o,\$(TEST_OBJ_DIR)/%.o,\\
                      \$(filter-out \$(BUILD_DIR)/microdlna.o,\$(filter %.o,\$(DST))))

TEST_SAN := -fsanitize=address,undefined -fno-omit-frame-pointer
TEST_CFLAGS := \$(BASE_CFLAGS) -g -O0 -I. -I\$(TEST_DIR)/support \$(TEST_SAN)
TEST_LDFLAGS := -pthread \$(TEST_SAN)

\$(TEST_OBJ_DIR) \$(TEST_BIN_DIR):
${tab}mkdir -p \$@

# Without this, make treats test .o files as disposable "intermediate"
# files (built only to satisfy a pattern-rule chain) and deletes them right
# after linking each test binary, forcing a full rebuild on every "make
# check". .SECONDARY with no prerequisites disables that for every file.
.SECONDARY:

\$(TEST_OBJ_DIR)/%.o: %.c | \$(TEST_OBJ_DIR)
${tab}\$(CC) -c \$(TEST_CFLAGS) -MMD -MP \$< -o \$@

\$(TEST_OBJ_DIR)/support_%.o: \$(TEST_DIR)/support/%.c | \$(TEST_OBJ_DIR)
${tab}\$(CC) -c \$(TEST_CFLAGS) -MMD -MP \$< -o \$@

\$(TEST_OBJ_DIR)/test_%.o: \$(TEST_DIR)/test_%.c | \$(TEST_OBJ_DIR)
${tab}\$(CC) -c \$(TEST_CFLAGS) -MMD -MP \$< -o \$@

\$(TEST_BIN_DIR)/test_%: \$(TEST_OBJ_DIR)/test_%.o \$(TEST_SUPPORT_OBJS) \\
                        \$(TEST_MODULE_OBJS) | \$(TEST_BIN_DIR)
${tab}\$(CC) \$(TEST_CFLAGS) -o \$@ \$(TEST_OBJ_DIR)/test_\$*.o \$(TEST_SUPPORT_OBJS) \\
${tab}  \$(filter-out \$(TEST_OBJ_DIR)/\$*.o,\$(TEST_MODULE_OBJS)) \$(TEST_LDFLAGS)

.PHONY: check test
check: \$(TEST_BINS)
${tab}@fail=0; for t in \$(TEST_BINS); do \\
${tab}    printf '== %s\\n' "\$\$t"; "\$\$t" || fail=1; \\
${tab}  done; \\
${tab}  if [ \$\$fail -ne 0 ]; then echo 'TESTS FAILED'; exit 1; fi; \\
${tab}  echo 'ALL TESTS PASSED'

test: check

-include \$(wildcard \$(TEST_OBJ_DIR)/*.d)

# ---- functional tests -----------------------------------------------------
# tests/functional/ftest_*.c drive a *real*, separately-running microdlnad
# process over real sockets (HTTP/SOAP over TCP, SSDP over UDP) -- see
# tests/functional/support/ and docs/dev/FUNCTIONAL_TESTS.md. Unlike the
# unit tests above, these binaries never link any of microdlna's own .o
# files; they only need the production binary built and spawned as a
# child process (tests/functional/support/process.c). Kept as a separate
# "make check-functional" target (not a dependency of check/test) since it
# is much slower: real process spawns, real socket round-trips.
FTEST_DIR := tests/functional
FTEST_OBJ_DIR := \$(BUILD_DIR)/tests/functional/obj
FTEST_BIN_DIR := \$(BUILD_DIR)/tests/functional/bin
FTEST_SAN_BIN_DIR := \$(BUILD_DIR)/tests/functional/sanitized

FTEST_SRCS := \$(wildcard \$(FTEST_DIR)/ftest_*.c)
FTEST_BINS := \$(patsubst \$(FTEST_DIR)/ftest_%.c,\$(FTEST_BIN_DIR)/ftest_%,\$(FTEST_SRCS))
FTEST_SUPPORT_SRCS := \$(wildcard \$(FTEST_DIR)/support/*.c)
# support_test_main.o is the exact same object the unit tests above build
# (tests/support/test_main.c has no unit-test-specific logic -- just
# TEST()/registration/running/filtering) -- reused here via its existing
# pattern rule rather than recompiled a second time.
FTEST_SUPPORT_OBJS := \$(TEST_OBJ_DIR)/support_test_main.o \\
                      \$(patsubst \$(FTEST_DIR)/support/%.c,\$(FTEST_OBJ_DIR)/fsupport_%.o,\$(FTEST_SUPPORT_SRCS))

FTEST_SAN := -fsanitize=address,undefined -fno-omit-frame-pointer
FTEST_CFLAGS := \$(BASE_CFLAGS) -g -O0 \$(FTEST_SAN)
FTEST_LDFLAGS := -pthread \$(FTEST_SAN)

\$(FTEST_OBJ_DIR) \$(FTEST_BIN_DIR):
${tab}mkdir -p \$@

\$(FTEST_OBJ_DIR)/fsupport_%.o: \$(FTEST_DIR)/support/%.c | \$(FTEST_OBJ_DIR)
${tab}\$(CC) -c \$(FTEST_CFLAGS) -MMD -MP \$< -o \$@

\$(FTEST_OBJ_DIR)/ftest_%.o: \$(FTEST_DIR)/ftest_%.c | \$(FTEST_OBJ_DIR)
${tab}\$(CC) -c \$(FTEST_CFLAGS) -MMD -MP \$< -o \$@

\$(FTEST_BIN_DIR)/ftest_%: \$(FTEST_OBJ_DIR)/ftest_%.o \$(FTEST_SUPPORT_OBJS) | \$(FTEST_BIN_DIR)
${tab}\$(CC) \$(FTEST_CFLAGS) -o \$@ \$(FTEST_OBJ_DIR)/ftest_\$*.o \$(FTEST_SUPPORT_OBJS) \$(FTEST_LDFLAGS)

# check-functional runs the ftest_* binaries against a *separate*,
# ASan/UBSan-instrumented build of microdlnad, in its own build directory
# so it never touches \$(BUILD_DIR)/microdlnad -- this is what lets live
# traffic through these tests catch the same class of bug the unit tests
# already catch per translation unit (see docs/dev/TESTS.md).
.PHONY: check-functional
check-functional: \$(FTEST_BINS)
${tab}\$(MAKE) BUILD_DIR=\$(FTEST_SAN_BIN_DIR) \\
${tab}  CFLAGS_DEV="\$(CFLAGS_DEV) \$(FTEST_SAN)" LDFLAGS_DEV="\$(LDFLAGS_DEV) \$(FTEST_SAN)" \\
${tab}  \$(FTEST_SAN_BIN_DIR)/microdlnad
${tab}@fail=0; for t in \$(FTEST_BINS); do \\
${tab}    printf '== %s\\n' "\$\$t"; \\
${tab}    MICRODLNAD_BIN=\$(FTEST_SAN_BIN_DIR)/microdlnad "\$\$t" || fail=1; \\
${tab}  done; \\
${tab}  if [ \$\$fail -ne 0 ]; then echo 'FUNCTIONAL TESTS FAILED'; exit 1; fi; \\
${tab}  echo 'ALL FUNCTIONAL TESTS PASSED'

-include \$(wildcard \$(FTEST_OBJ_DIR)/*.d)

MAKEFILE
